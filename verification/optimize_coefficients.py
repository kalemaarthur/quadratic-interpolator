#!/usr/bin/env python3
"""Preview or apply 3-point quadratic interpolation coefficients.

Run from any working directory:
  python3 verification/optimize_coefficients.py
  python3 verification/optimize_coefficients.py --apply

Preserves the existing Q formats and SystemVerilog datapath.
Requires Python standard library only.
"""

from __future__ import annotations

import argparse
import math
import random
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HERE = Path(__file__).resolve().parent
BACKUP = HERE / 'backup-original-coefficients'
SEGMENTS = 128
INPUT_WIDTH = 24
FRACTIONAL_INPUT_BITS = 23
STEP = 1.0 / 64.0
FORMATS = {'a': (23, 22), 'b': (19, 16), 'c': (12, 10)}


def sine(x: float) -> float:
    return math.sin(2.0*x - math.pi/4.0)


def signed(word: int, bits: int) -> int:
    word &= (1 << bits) - 1
    return word - (1 << bits) if word & (1 << (bits - 1)) else word


def quantize(value: float, width: int, frac: int) -> int:
    quantized = round(value * (1 << frac))  # ties to even
    min_val, max_val = -(1 << (width - 1)), (1 << (width - 1)) - 1
    if not min_val <= quantized <= max_val:
        raise ValueError(f'Coefficient {value:.12g} exceeds s{width-frac}.{frac} range')
    return quantized


def optimized_coefficients() -> dict[str, list[int]]:
    coeffs = {key: [] for key in FORMATS}
    for k in range(SEGMENTS):
        x0 = k * STEP
        y0, ym, ye = sine(x0), sine(x0 + STEP/2.0), sine(x0 + STEP)
        a = y0
        b = (4.0*ym - 3.0*y0 - ye) / STEP
        c = 2.0*(ye + y0 - 2.0*ym) / (STEP*STEP)
        for key, value in zip(('a','b','c'), (a,b,c)):
            coeffs[key].append(quantize(value, *FORMATS[key]))
    return coeffs


def load_coefficients() -> dict[str, list[int]]:
    coeffs = {}
    for key, (width, _frac) in FORMATS.items():
        filename = ROOT / f'{key}.mem'
        vals = [signed(int(line.strip(), 16), width)
                for line in filename.read_text().splitlines() if line.strip()]
        if len(vals) != SEGMENTS:
            raise ValueError(f'Expected {SEGMENTS} entries in {filename}, found {len(vals)}')
        coeffs[key] = vals
    return coeffs


def model(raw_x: int, rom: dict[str, list[int]]) -> int:
    """Bit-exact model of the existing RTL datapath; result is a 25-bit word."""
    index = raw_x >> 17
    x2 = raw_x & 0x1ffff
    sq = (x2 * x2) >> 22
    summation = ((rom['a'][index] << 5)
                 + ((rom['b'][index] * x2) >> 12)
                 + ((rom['c'][index] * sq) >> 7))
    summation = signed(summation, 29)
    base = summation >> 4
    guard = (summation >> 3) & 1
    sticky = bool(summation & 7)
    rounded = base + int(bool(guard and (sticky or (base & 1))))
    return rounded & ((1 << 25) - 1)


def sample_vectors() -> list[int]:
    values = [0x000000, 0x400000, 0x7fffff, 0x800000, 0xc00000, 0xffffff]
    for k in range(SEGMENTS):
        start = k << 17
        for x in (start-1, start, start+1, start+0x1ffff):
            if 0 <= x <= 0xffffff:
                values.append(x)
    rng = random.Random(20261120)
    ordered = list(dict.fromkeys(values))
    seen = set(ordered)
    while len(ordered) < 2048:
        x = rng.randrange(1 << INPUT_WIDTH)
        if x not in seen:
            ordered.append(x)
            seen.add(x)
    return ordered


def max_error(rom: dict[str, list[int]], inputs: list[int]) -> tuple[float,int,int]:
    worst = (0.0, 0, 0)
    count = 0
    for x in inputs:
        as_real = signed(model(x, rom), 25) / (1 << 23)
        target = sine(x / (1 << 23))
        err = abs(as_real - target)
        if err >= 2.15e-6:
            count += 1
        if err > worst[0]:
            worst = (err, x, count)
    return worst[0], worst[1], count


def make_mem(key: str, values: list[int]) -> str:
    width, _frac = FORMATS[key]
    nibbles = (width + 3) // 4
    return ''.join(f'{v & ((1 << width)-1):0{nibbles}X}\n' for v in values)


def make_cpp_table(coeffs: dict[str, list[int]]) -> str:
    lines = [
        '// Auto-generated by verification/optimize_coefficients.py',
        '// Three-point interpolation at start, midpoint, end of each 1/64-wide segment.',
        '// Quantized exactly as RTL ROMs: a=s1.22, b=s3.16, c=s2.10.',
        'const double CoeffTable [128][4] =',
        '{',
    ]
    for k in range(SEGMENTS):
        q = [coeffs[key][k] / (1 << FORMATS[key][1]) for key in ('a','b','c')]
        lines.append(f'    {{ {k:3d}, {q[0]: .20f}, {q[1]: .20f}, {q[2]: .20f} }},')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def apply(coeffs: dict[str, list[int]]) -> None:
    files = [ROOT / f'{key}.mem' for key in ('a','b','c')]
    files.extend(ROOT / 'rtl-model' / f'{key}.mem' for key in ('a','b','c'))
    files.append(ROOT / 'c++-model' / 'CoeffTable.hpp')
    for f in files:
        if not f.is_file():
            raise FileNotFoundError(f'Expected repository file missing: {f}')
    if not BACKUP.exists():
        BACKUP.mkdir(parents=True)
        for f in files:
            dest = BACKUP / f.relative_to(ROOT)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, dest)
        print('Original coefficients backed up in verification/backup-original-coefficients/')
    else:
        print('Original backup exists; preserving it unchanged.')
    for key in ('a','b','c'):
        payload = make_mem(key, coeffs[key])
        for path in (ROOT / f'{key}.mem', ROOT / 'rtl-model' / f'{key}.mem'):
            path.write_text(payload)
    (ROOT / 'c++-model' / 'CoeffTable.hpp').write_text(make_cpp_table(coeffs))
    print('Updated 6 .mem files and c++-model/CoeffTable.hpp (no RTL edits).')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true', help='Back up then write optimized coefficients')
    args = parser.parse_args()
    old = load_coefficients()
    new = optimized_coefficients()
    samples = sample_vectors()
    for name, rom in (('Current', old), ('Proposed', new)):
        worst, x, fails = max_error(rom, samples)
        print(f'{name} 2048-vector error: {worst:.9g} at 0x{x:06x}; values >= 2.15e-6: {fails}')
    dense = range(0, 1 << 24, 128)
    worst, x, fails = max_error(new, list(dense))
    print(f'Proposed 131072-point sweep error: {worst:.9g} at 0x{x:06x}; values >= 2.15e-6: {fails}')
    if args.apply:
        apply(new)
        print('Next: python3 verification/verify_rtl.py')
    else:
        print('Preview only. To apply: python3 verification/optimize_coefficients.py --apply')


if __name__ == '__main__':
    main()
